// Real-browser checks for bounded lists, demand rendering and reusable shadows.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { auditBrowser, sleep } from "./audit_browser.mjs";
const base = process.argv[2] ?? "http://127.0.0.1:8765";
const out = process.argv[3] ?? "/tmp/horologium-optimization";
const browser = await auditBrowser(out);
const { send, evaluate, wait, shot, assert, problems } = browser;
const reports = [];
const go = async path => {
  await evaluate(`window.__horologium.router.go(${JSON.stringify(path)})`);
  await wait(`location.pathname+location.search===${JSON.stringify(path)} && !!document.querySelector('h1')`);
};
try {
  await send("Emulation.setCPUThrottlingRate", { rate: 4 });
  await send("Page.addScriptToEvaluateOnNewDocument", { source: "Object.defineProperty(navigator,'hardwareConcurrency',{value:8,configurable:true});Object.defineProperty(navigator,'deviceMemory',{value:8,configurable:true})" });
  await send("Page.navigate", { url: base + "/movements" });
  await wait("!!document.querySelector('#mgrid') && !document.querySelector('#intro')");
  assert(await evaluate("document.querySelectorAll('.mcard').length===12"), "calibre list is not bounded on entry");
  reports.push({ catalogue: await evaluate("({cards:document.querySelectorAll('.mcard').length,elements:document.querySelectorAll('*').length})") });
  await evaluate("document.querySelector('#movement-more').click()");
  assert(await evaluate("document.querySelectorAll('.mcard').length===24 && location.search.includes('shown=24')"), "next calibre batch is missing or not saved");
  await go("/learn");
  await evaluate("history.back()");
  await wait("location.pathname==='/movements' && document.querySelectorAll('.mcard').length===24");
  const last = await evaluate("fetch('/api/v1/movements').then(r=>r.json()).then(rows=>rows.at(-1))");
  await evaluate(`document.querySelector('#msearch').value=${JSON.stringify(last.caliber)};document.querySelector('#msearch').dispatchEvent(new Event('input',{bubbles:true}))`);
  assert(await evaluate(`!!document.querySelector('.mcard[data-slug="${last.slug}"]')`), "search does not include undisplayed calibres");
  await evaluate("document.querySelector('#mreset').click()");
  assert(await evaluate("!location.search && document.querySelectorAll('.mcard').length===12 && document.activeElement.id==='msearch' && !document.querySelector('#mreset').getClientRects().length"), "reset did not restore a usable bounded catalogue");
  for (const width of [390, 1440]) {
    await send("Emulation.setDeviceMetricsOverride", { width, height: width < 700 ? 844 : 1000, deviceScaleFactor: 1, mobile: width < 700 });
    await evaluate("scrollTo({top:0,behavior:'instant'})"); await sleep(800);
    assert(await evaluate(`document.documentElement.scrollWidth<=${width}+1`), `${width}: calibre overflow`);
    await shot(`${width}-calibres`);
  }
  await go("/");
  await wait("!!window.__horologium.globe.scene?.ready");
  await sleep(7000);
  const before = await evaluate("({frame:__horologium.globe.scene.renderer.info.render.frame,suspended:!!__horologium.globe.scene.ambientSuspended})");
  await sleep(1000);
  const delta = await evaluate(`__horologium.globe.scene.renderer.info.render.frame-${before.frame}`);
  assert(before.suspended ? delta <= 1 : delta <= 36, "idle overview exceeds its ambient frame budget");
  reports.push({ overview: { framesInOneSecond: delta, ambientSuspended: before.suspended } });
  assert(await evaluate("!performance.getEntriesByType('resource').some(r=>r.name.includes('day-8k'))"), "overview eagerly loaded the high-resolution texture");
  await shot("1440-overview");
  await evaluate("__horologium.globe.scene.preview('CHE')");
  await wait(`__horologium.globe.scene.renderer.info.render.frame>${before.frame + delta}`);
  const point = await evaluate("(() => {for(let y=160;y<innerHeight-80;y+=100)for(let x=80;x<innerWidth-80;x+=100)if(document.elementFromPoint(x,y)?.id==='globe-canvas')return {x,y};})()");
  assert(!!point, "globe has no interactive canvas area");
  if (point) {
    const lon = await evaluate("__horologium.globe.scene.rig.lon");
    await send("Input.dispatchMouseEvent", { type: "mousePressed", ...point, button: "left", buttons: 1, clickCount: 1 });
    await send("Input.dispatchMouseEvent", { type: "mouseMoved", x: point.x + 45, y: point.y + 12, button: "left", buttons: 1 });
    await send("Input.dispatchMouseEvent", { type: "mouseReleased", x: point.x + 45, y: point.y + 12, button: "left", clickCount: 1 });
    assert(await evaluate(`Math.abs(__horologium.globe.scene.rig.lon-${lon})>0.1`), "sleeping globe did not wake for dragging");
  }
  await go("/country/switzerland");
  await wait("__horologium.globe.scene.focused?.iso_a3==='CHE' && !!__horologium.globe.scene.countryLayer");
  await wait("!__horologium.globe.scene.running");
  const countryFrame = await evaluate("__horologium.globe.scene.renderer.info.render.frame");
  await sleep(1000);
  assert(await evaluate(`__horologium.globe.scene.renderer.info.render.frame===${countryFrame}`), "stationary country keeps rendering");
  assert(await evaluate("__horologium.globe.scene.borderMats.length>0 && __horologium.globe.scene.pinClusters.length>0"), "country borders or brand markers disappeared");
  reports.push({ country: "stationary renderer asleep; borders and pins retained" });
  await evaluate("window.__countryLayerBefore=__horologium.globe.scene.countryLayer;document.querySelector('#cur-btn').click();document.querySelector('[data-cur=EUR]').click();void 0");
  assert(await evaluate("__horologium.globe.scene.countryLayer===window.__countryLayerBefore && [...document.querySelectorAll('[data-price-usd]')].every(e=>e.textContent.includes('€'))"), "currency recreated the country layer or left old prices");
  await shot("1440-switzerland");
  await send("Emulation.setEmulatedMedia", { features: [{ name: "prefers-reduced-motion", value: "reduce" }] });
  await go("/");
  await wait("!__horologium.globe.scene.running");
  const reducedFrame = await evaluate("__horologium.globe.scene.renderer.info.render.frame");
  await sleep(1000);
  assert(await evaluate(`__horologium.globe.scene.renderer.info.render.frame===${reducedFrame}`), "reduced-motion overview keeps rendering");
  await go("/watch/rolex-submariner");
  await evaluate("document.querySelector('.sub-workshop').scrollIntoView({block:'start',behavior:'instant'})");
  await wait("!!__horologium.submariner?.parts.length");
  await sleep(1800);
  await evaluate("__horologium.submariner.renderer.shadowMap.needsUpdate=true;__horologium.submariner.request()");
  await sleep(700);
  const fullCalls = await evaluate("__horologium.submariner.renderer.info.render.calls");
  await evaluate("window.__poseBefore=__horologium.submariner.parts[0].pose;__horologium.submariner.zoom(0.95)");
  await sleep(700);
  const orbit = await evaluate("({calls:__horologium.submariner.renderer.info.render.calls,samePose:__horologium.submariner.parts[0].pose===window.__poseBefore,shadowClean:!__horologium.submariner.renderer.shadowMap.needsUpdate})");
  assert(orbit.calls < fullCalls && orbit.samePose && orbit.shadowClean, "camera movement recalculated geometry or shadows");
  await evaluate("__horologium.submariner.setT(4/7,true)");
  await sleep(900);
  assert(await evaluate("__horologium.submariner.parts[0].pose!==window.__poseBefore"), "moving parts failed to invalidate the pose");
  await evaluate("__horologium.submariner.isolate(__horologium.submariner.parts[0].id);__horologium.submariner.view('front',true)");
  await sleep(700);
  assert(await evaluate("__horologium.submariner.parts.every(p=>p.node.visible) && !__horologium.submariner.renderer.shadowMap.needsUpdate"), "restoring parts left stale visibility or shadows");
  reports.push({ workshop: { fullCalls, cameraCalls: orbit.calls, samePose: orbit.samePose } });
  await evaluate("window.__sceneBeforeCurrency=__horologium.submariner;window.__cameraBeforeCurrency=__horologium.submariner.camera.position.toArray();document.querySelector('#cur-btn').click();document.querySelector('[data-cur=KZT]').click();void 0");
  await sleep(500);
  assert(await evaluate("__horologium.submariner===window.__sceneBeforeCurrency && __horologium.submariner.camera.position.toArray().every((v,i)=>v===window.__cameraBeforeCurrency[i]) && [...document.querySelectorAll('[data-price-usd]')].every(e=>e.textContent.includes('₸')) && !document.querySelector('.wprice__fx').hidden"), "currency recreated the workshop or left old amounts");
  await evaluate("document.querySelector('#cur-btn').click();document.querySelector('[data-cur=USD]').click()");
  assert(await evaluate("document.querySelector('.wprice__fx').hidden && __horologium.submariner===window.__sceneBeforeCurrency"), "USD did not restore the price note without rebuilding 3D");
  reports.push({ currency: "country and workshop instances retained; all tagged prices updated" });
  await shot("1440-workshop");
  await evaluate("window.__oldScene=__horologium.submariner;void 0");
  await go("/movements");
  assert(await evaluate("window.__oldScene.dead && !__horologium.submariner"), "workshop resources survived navigation");
  await go("/tco?watch=rolex-submariner");
  await evaluate("document.querySelector('#cur-btn').click();document.querySelector('[data-cur=EUR]').click()");
  assert(await evaluate("document.querySelector('.tco-selected-info [data-price-usd]').textContent.includes('€') && document.querySelector('#tco-select-watch').selectedOptions[0].textContent.includes('€') && document.querySelector('#tco-net-tco-val').textContent.includes('€')"), "TCO preview, selector and result use different currencies");
} catch (error) { problems.push(error.stack); }
finally { await browser.close(); }
writeFileSync(join(out, "report.json"), JSON.stringify({ reports, problems }, null, 2));
console.log(JSON.stringify({ reports, problems }, null, 2));
if (problems.length) process.exitCode = 1;
